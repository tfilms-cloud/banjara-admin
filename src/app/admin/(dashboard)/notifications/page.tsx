"use client";

import { useMemo, useState } from "react";
import { Bell } from "lucide-react";
import { EmptyState } from "@/components/empty-state";
import { ErrorState } from "@/components/error-state";
import { TableSkeleton } from "@/components/loading-skeleton";
import { PageHeader } from "@/components/page-header";
import { SearchInput } from "@/components/search-input";
import { StatusBadge } from "@/components/status-badge";
import { Button } from "@/components/ui/button";
import { useDebouncedValue } from "@/hooks/useDebouncedValue";
import { useNotifications } from "@/hooks/useNotifications";
import { filterByPaths, firstText, refLabel } from "@/lib/records";
import { formatDateTime, idOf } from "@/lib/utils";

const SEARCH_PATHS = ["title", "message", "body", "type", "userId.name"];

export default function NotificationsPage() {
  const [search, setSearch] = useState("");
  const debouncedSearch = useDebouncedValue(search);
  const { data, isPending, isError, error, refetch, isFetching } = useNotifications();

  const rows = useMemo(
    () => filterByPaths(data ?? [], debouncedSearch, SEARCH_PATHS),
    [data, debouncedSearch]
  );

  return (
    <div className="space-y-5">
      <PageHeader
        title="Notifications"
        description="System and platform notifications delivered to BANJARA users."
        actions={
          <Button variant="outline" size="sm" onClick={() => void refetch()} loading={isFetching}>
            Refresh
          </Button>
        }
      />

      <SearchInput value={search} onChange={setSearch} placeholder="Search notifications…" />

      <div className="overflow-hidden rounded-xl border border-border bg-card shadow-sm">
        {isPending ? (
          <TableSkeleton columns={3} />
        ) : isError ? (
          <ErrorState error={error} onRetry={() => void refetch()} retrying={isFetching} />
        ) : rows.length ? (
          <ul className="divide-y divide-border">
            {rows.map((notification, index) => {
              const type = firstText(notification, ["type", "category"], "");
              const recipient = refLabel(
                (notification as Record<string, unknown>)?.userId,
                ""
              );
              return (
                <li
                  key={idOf(notification) || `notification-${index}`}
                  className="flex flex-col gap-2 px-5 py-4 sm:flex-row sm:items-start sm:justify-between"
                >
                  <div className="flex min-w-0 gap-3">
                    <span className="mt-0.5 flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-sky/10 text-sky">
                      <Bell className="h-4 w-4" aria-hidden />
                    </span>
                    <div className="min-w-0">
                      <p className="text-sm font-medium text-navy">
                        {firstText(notification, ["title", "subject"], "Notification")}
                      </p>
                      <p className="text-sm text-muted">
                        {firstText(notification, ["message", "body", "content"])}
                      </p>
                      {recipient && recipient !== "—" ? (
                        <p className="mt-1 text-xs text-muted">To: {recipient}</p>
                      ) : null}
                    </div>
                  </div>
                  <div className="flex shrink-0 items-center gap-2 sm:flex-col sm:items-end">
                    {type && type !== "—" ? <StatusBadge status={type} /> : null}
                    <span className="text-xs text-muted">
                      {formatDateTime(firstText(notification, ["createdAt", "sentAt"], ""))}
                    </span>
                  </div>
                </li>
              );
            })}
          </ul>
        ) : (
          <EmptyState
            icon={Bell}
            title="No notifications"
            description="Notifications generated by the platform will appear here."
          />
        )}
      </div>
    </div>
  );
}
